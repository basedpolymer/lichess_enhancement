#!/usr/bin/env node
//BUILDS ressources/preview/index.html FROM THE CATALOG (ressources/js/catalog.js),
//SO THE PREVIEW ALWAYS SHOWS EXACTLY THE SETS THE USER CAN PICK
//Usage (from the repo root): node scripts/buildPreview.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CATALOG = require('../ressources/js/catalog.js');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

//Group "Chess.com - Bots" -> { 'Chess.com': [{ sub: 'Bots', options: [{ value, label }] }] }
function readGroups(kind) {
  const map = new Map();
  for (const g of CATALOG[kind]) {
    const [source, sub] = g.group.split(' - ');
    const options = g.items.map(([value, label]) => ({ value, label }));
    if (!map.has(source)) map.set(source, []);
    map.get(source).push({ sub: sub || null, options });
  }
  return map;
}

const pieces = readGroups('pieces');
const boards = readGroups('board');

const PIECES_SHOWN = [
  ['br', 'Black rook'],
  ['bn', 'Black knight'],
  ['bb', 'Black bishop'],
  ['bq', 'Black queen'],
  ['bk', 'Black king'],
];

const pieceCard = ({ value, label }) => {
  const ext = value === 'random' ? 'gif' : 'webp';
  return `                <div class="style_p">
                    <div class="h_pre">
                        <span class="name">${esc(label)}</span>
                    </div>
                    <div class="images">
${PIECES_SHOWN.map(
  ([p, alt]) => `                        <img class="piece_url" loading="lazy" src="../pieces/${value}/${p}.${ext}" alt="${alt}" />`
).join('\n')}
                    </div>
                </div>`;
};

const boardCard = ({ value, label }) => `                <div class="style_b">
                    <div class="h_pre">
                        <span class="name">${esc(label)}</span>
                    </div>
                    <div class="images">
                        <img class="board_img" loading="lazy" src="../boards/${value}.webp" alt="Board">
                    </div>
                </div>`;

//One column of cards; sub-groups (Events & sports, Bots) get a heading
function list(cls, groups, card) {
  const body = (groups || [])
    .map((g) =>
      [g.sub ? `                <h3 class="sub_title">${esc(g.sub)}</h3>` : null, ...g.options.map(card)]
        .filter(Boolean)
        .join('\n')
    )
    .join('\n');
  return `            <div class="${cls}"><hr />
${body}
            </div>`;
}

//The sources added after those above: a title (with the logo of the source when it has one) over a column of
//pieces and, for some, a column of boards. first: its first column in the grid of main.css
const EXTRA = [
  { source: 'Lucas Chess', first: 18, logo: 'lucas_chess.png' },
  { source: 'HollowLeaf', first: 20 },
  { source: 'ChessSkins', first: 22, logo: 'chessskins.png', boards: true },
  { source: 'WBChess', first: 25, logo: 'wbchess.png' },
  { source: 'Noun Project', first: 27 },
];

const at = (cls, column) => `${cls}" style="grid-column: ${column}`;

function extraSection({ source, first, logo, boards: hasBoards }) {
  const img = logo ? `<img src="../logo/${logo}" alt="" width=56 height=56 />` : '';
  return [
    `            <h3 class="${at('src_title', hasBoards ? `${first} / ${first + 2}` : first)}">${img}${esc(source)}</h3>`,
    list(at('col_p', first), pieces.get(source), pieceCard),
    hasBoards ? list(at('col_b', first + 1), boards.get(source), boardCard) : null,
  ]
    .filter(Boolean)
    .join('\n\n');
}

const html = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Preview - Lichess enhancement</title>
    <link rel="stylesheet" href="main.css">
</head>
<body>
    <!-- GENERATED by scripts/buildPreview.js from ressources/js/catalog.js: edit the catalog, then re-run the script -->
    <center>
        <h1>
            <picture>
                <source srcset="../logo/lichess_chess_logo_white.png" media="(prefers-color-scheme: dark)">
                <img src="../logo/lichess_chess_logo.png" width="300" alt="Lichess enhancement"/>
            </picture>
        </h1>
        <div style="font-size: 1.3em;font-style:italic">Unofficial lichess enhancement / <a href="https://github.com/basedpolymer/lichess_enhancement">Github</a></div>

        <h2>Preview style pieces/boards</h2>
    </center>

        <br />
        <div class="list">

            <img class="logo_chesscom" src="../logo/chesscom_logo_filled.png" alt="logo chess.com" width=200/>

${list('list_p_chess', pieces.get('Chess.com'), pieceCard)}

${list('list_b_chess', boards.get('Chess.com'), boardCard)}

            <img class="logo_chessfoundry" src="../logo/chessfoundry.svg" alt="logo chessfoundry" width=100/>

${list('list_p_chessfoundry', pieces.get('Chessfactory'), pieceCard)}

            <h3 class="maurizio_title">Maurizio</h3>

${list('list_p_maurizio', pieces.get('Maurizio Monge'), pieceCard)}

            <h3 class="community_title">Community</h3>

${list('list_p_community', pieces.get('Community'), pieceCard)}

${list('list_b_community', boards.get('Community'), boardCard)}

            <h3 class="lneo_title"><img src="../logo/lichess_neo.png" alt="" width=64 height=64 />Lichess Neo</h3>

${list('list_p_lneo', pieces.get('Lichess Neo'), pieceCard)}

${list('list_b_lneo', boards.get('Lichess Neo'), boardCard)}

            <picture class="logo_lichess">
                <source srcset="../logo/lichess_org_white.png" media="(prefers-color-scheme: dark)">
                <img src="../logo/lichess_org.png" alt="lichess.org" width=260 />
            </picture>

${list('list_p_lichess', pieces.get('Lichess'), pieceCard)}

${list('list_b_lichess', boards.get('Lichess'), boardCard)}

${EXTRA.map(extraSection).join('\n\n')}
        </div>
        <br />
</body>
</html>
`;

const known = new Set(['Chess.com', 'Chessfactory', 'Maurizio Monge', 'Community', 'Lichess Neo', 'Lichess', ...EXTRA.map((e) => e.source)]);
for (const source of [...pieces.keys(), ...boards.keys()]) {
  if (!known.has(source)) throw new Error(`No column for the catalog group "${source}": add one to buildPreview.js`);
}

for (const e of EXTRA) {
  if (boards.has(e.source) && !e.boards) throw new Error(`"${e.source}" has boards but no boards column in buildPreview.js`);
}

fs.writeFileSync(path.join(ROOT, 'ressources/preview/index.html'), html);
const total = (m) => [...m.values()].flat().reduce((n, g) => n + g.options.length, 0);
console.log(`preview: ${total(pieces)} piece sets, ${total(boards)} boards`);
